#!/bin/sh
# Unique Secure Boot key for this site, and the enroll/sign steps.
#
# The key is generated on the operator machine. It is not in git. Each site
# gets its own. Do not reuse a key from another cluster.
#
#   deploy/kata/secureboot.sh --init --dir /etc/nvkvm-kata/secureboot
#   # rebuild the guest so the kernel trusts db.pem (see --fragment)
#   deploy/kata/secureboot.sh --sign-kernel --dir /etc/nvkvm-kata/secureboot /path/vmlinuz
#   deploy/kata/secureboot.sh --sign-module --dir /etc/nvkvm-kata/secureboot \
#       --kbuild /path/kata-linux-nvkvm /path/nvkvm-guest.ko
#   deploy/kata/secureboot.sh --enroll --dir /etc/nvkvm-kata/secureboot \
#       --template /usr/share/edk2/ovmf/OVMF_VARS.fd \
#       --out /etc/nvkvm-kata/secureboot/OVMF_VARS.custom.fd
#
# Then point the shim at the enrolled store and refuse an unsigned boot:
#
#   GS_UEFI_TEMPLATE=/etc/nvkvm-kata/secureboot/OVMF_VARS.custom.fd
#   GS_SB_ENFORCE=1
#
# Delete <PERSIST_ROOT>/<login>/uefi/OVMF_VARS.fd afterwards. The shim copies
# the template only when that file is missing. An old store still has Secure
# Boot off. Kata's kernel path has to be the signed EFI stub (sbsign output).
# OVMF checks that image. A raw unsigned bzImage will not boot once the
# enrolled store has Secure Boot on. CONFIG_EFI_STUB is already in the
# desktop fragment. CONFIG_MODULE_SIG_FORCE is not: an unsigned
# nvkvm-guest.ko would remove the GPU. Sign the module, then pass
# --force-modules if you want the kernel to reject anything else.
set -eu

die() {
    echo "secureboot: $*" >&2
    exit 1
}

dir=/etc/nvkvm-kata/secureboot
template=""
out=""
kbuild=""
force=0
mode=""
target=""

while [ $# -gt 0 ]; do
    case "$1" in
        --init|--enroll|--sign-kernel|--sign-module|--fragment|--self-test)
            mode=${1#--}
            ;;
        --dir)
            dir=$2
            shift
            ;;
        --template)
            template=$2
            shift
            ;;
        --out)
            out=$2
            shift
            ;;
        --kbuild)
            kbuild=$2
            shift
            ;;
        --force-modules)
            force=1
            ;;
        --)
            shift
            break
            ;;
        -*)
            die "unknown option $1"
            ;;
        *)
            target=$1
            ;;
    esac
    shift
done

enroll_cmd() {
    # Custom mode: a PK is enrolled, so the firmware is not in Setup Mode.
    # The same site cert is PK, KEK, and db. virt-fw-vars writes the store.
    printf '%s\n' \
        virt-fw-vars \
        --input "$template" \
        --output "$out" \
        --secure-boot \
        --set-pk "$dir/db.pem" \
        --add-kek "$dir/db.pem" \
        --add-db "$dir/db.pem"
}

write_fragment() {
    cat <<EOF
# Generated by deploy/kata/secureboot.sh. Not part of the committed fragment.
# Point the kernel build at this site's key, then sign nvkvm-guest.ko with it.
CONFIG_MODULE_SIG=y
CONFIG_MODULE_SIG_ALL=y
CONFIG_MODULE_SIG_SHA256=y
CONFIG_MODULE_SIG_KEY="$dir/db.key"
CONFIG_SYSTEM_TRUSTED_KEYRING=y
CONFIG_SYSTEM_TRUSTED_KEYS="$dir/db.pem"
EOF
    if [ "$force" = 1 ]; then
        echo "CONFIG_MODULE_SIG_FORCE=y"
    fi
}

init_keys() {
    [ -e "$dir/db.key" ] && die "$dir/db.key already exists; refusing to replace a site key"
    mkdir -p "$dir"
    chmod 0700 "$dir"
    stamp=$(date -u +%Y%m%dT%H%M%SZ)
    raw=$(uname -n 2>/dev/null || echo site)
    host=$(printf '%s' "$raw" | tr -cd 'A-Za-z0-9.-')
    [ -n "$host" ] || host=site
    cn="sunslop-db-${host}-${stamp}"
    openssl req -x509 -newkey rsa:2048 -nodes -sha256 \
        -keyout "$dir/db.key" -out "$dir/db.crt" -days 3650 \
        -subj "/CN=${cn}/" >/dev/null 2>&1
    openssl x509 -in "$dir/db.crt" -out "$dir/db.pem"
    openssl x509 -in "$dir/db.crt" -outform DER -out "$dir/db.cer"
    chmod 0600 "$dir/db.key" "$dir/db.crt" "$dir/db.pem" "$dir/db.cer"
    echo "secureboot: wrote $dir (CN=$cn)"
    echo "secureboot: this key signs the guest kernel and nvkvm-guest.ko. Keep it off the seats."
}

case "$mode" in
    init)
        init_keys
        ;;
    fragment)
        [ -f "$dir/db.pem" ] || die "run --init first"
        write_fragment
        if [ "$force" != 1 ]; then
            echo "secureboot: MODULE_SIG_FORCE is off until nvkvm-guest.ko is signed with this key. Re-run with --force-modules after that." >&2
        fi
        ;;
    enroll)
        [ -f "$dir/db.pem" ] || die "run --init first"
        [ -n "$template" ] && [ -f "$template" ] || die "--template must be the empty OVMF_VARS.fd"
        [ -n "$out" ] || die "--out is required"
        command -v virt-fw-vars >/dev/null 2>&1 \
            || die "virt-fw-vars is not installed (Fedora: python3-virt-firmware)"
        virt-fw-vars \
            --input "$template" \
            --output "$out" \
            --secure-boot \
            --set-pk "$dir/db.pem" \
            --add-kek "$dir/db.pem" \
            --add-db "$dir/db.pem"
        echo "secureboot: enrolled custom mode into $out"
        echo "secureboot: set GS_UEFI_TEMPLATE=$out and GS_SB_ENFORCE=1"
        echo "secureboot: delete <PERSIST_ROOT>/<login>/uefi/OVMF_VARS.fd so the next seat copies this store"
        ;;
    sign-kernel)
        [ -f "$dir/db.key" ] || die "run --init first"
        [ -n "$target" ] && [ -f "$target" ] || die "pass the EFI stub vmlinuz"
        command -v sbsign >/dev/null 2>&1 || die "sbsign is not installed (sbsigntools)"
        dest=${out:-$target.signed}
        sbsign --key "$dir/db.key" --cert "$dir/db.crt" --output "$dest" "$target"
        echo "secureboot: signed kernel $dest"
        echo "secureboot: set Kata's kernel to that path. It has to be the EFI stub, not a raw bzImage."
        ;;
    sign-module)
        [ -f "$dir/db.key" ] || die "run --init first"
        [ -n "$kbuild" ] && [ -x "$kbuild/scripts/sign-file" ] || die "--kbuild must be the built guest kernel tree"
        [ -n "$target" ] && [ -f "$target" ] || die "pass nvkvm-guest.ko"
        "$kbuild/scripts/sign-file" sha256 "$dir/db.key" "$dir/db.cer" "$target"
        echo "secureboot: signed module $target"
        ;;
    self-test)
        tmp=$(mktemp -d)
        dir=$tmp/keys
        init_keys
        [ "$(stat -c %a "$dir")" = 700 ]
        [ -f "$dir/db.key" ] && [ -f "$dir/db.pem" ] && [ -f "$dir/db.cer" ]
        openssl x509 -in "$dir/db.crt" -noout -subject | grep -q "sunslop-db-"
        frag=$(write_fragment)
        printf '%s\n' "$frag" | grep -q 'CONFIG_SYSTEM_TRUSTED_KEYS='
        printf '%s\n' "$frag" | grep -q 'CONFIG_MODULE_SIG_FORCE' && die "force leaked into the default fragment"
        force=1
        write_fragment | grep -q '^CONFIG_MODULE_SIG_FORCE=y$'
        force=0
        template=$tmp/OVMF_VARS.fd
        out=$tmp/OVMF_VARS.custom.fd
        printf 'VARS' > "$template"
        enroll_cmd | grep -q -- '--secure-boot'
        enroll_cmd | grep -q -- '--set-pk'
        dir2=$tmp/keys2
        dir=$dir2
        init_keys
        a=$(openssl rsa -in "$tmp/keys/db.key" -modulus -noout)
        b=$(openssl rsa -in "$dir2/db.key" -modulus -noout)
        [ "$a" != "$b" ] || die "two sites produced the same key"
        rm -rf "$tmp"
        echo "self-test ok"
        ;;
    *)
        die "usage: secureboot.sh --init|--fragment|--enroll|--sign-kernel|--sign-module|--self-test"
        ;;
esac
